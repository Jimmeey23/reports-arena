import assert from 'node:assert/strict';
import { create, act } from 'react-test-renderer';
import { ReportMoMTable } from './ReportMoMTable';
import { register, reportDelta } from './adapter';

register({count:{label:'Visits',unit:'',description:'Attended visits'},rate:{label:'Fill',unit:'%',description:'Attended seats / capacity'}});
const history=Array.from({length:57},(_,i)=>({month:new Date(Date.UTC(2022,1+i,1)).toISOString().slice(0,7),count:100+i,rate:50+i/10}));
let selected='';
let tree:any;
act(()=>{tree=create(<ReportMoMTable history={history} ids={['count','rate']} selected="2026-09" onSelect={m=>selected=m} title="Test"/>);});
const root=()=>tree.root;
const headerCount=()=>root().findByType('thead').findAllByType('th').length;
assert.equal(headerCount(),58,'Default view includes all 57 months');
assert.equal(root().findByProps({'aria-label':'Monthly periods shown'}).props.value,0);
act(()=>tree.update(<ReportMoMTable history={history} ids={['count','rate']} selected="2023-01" onSelect={m=>selected=m} title="Test"/>));
assert.equal(headerCount(),58,'Selected report month only changes highlighting');
const first=root().findAllByProps({className:'monthly-value '})[0];
act(()=>first.props.onClick());
assert.equal(selected,'2026-10');
assert.equal(headerCount(),58,'Selecting a month does not truncate the table');
act(()=>root().findByProps({'aria-label':'Search monthly measures'}).props.onChange({target:{value:'Visits'}}));
assert.equal(root().findByType('tbody').findAllByType('tr').length,1);
act(()=>root().findByProps({'aria-label':'Search monthly measures'}).props.onChange({target:{value:''}}));
const mode=(text:string)=>root().findAllByType('button').find((b:any)=>b.children.length===1&&b.children[0]===text);
act(()=>mode('MoM Δ').props.onClick());
assert.equal(root().findByProps({'aria-label':'Monthly comparison display'}).findAllByProps({'aria-pressed':true})[0].children[0],'MoM Δ');
assert.equal(reportDelta('rate',60,50),'+10.0 pp');
act(()=>mode('YoY Δ').props.onClick());
act(()=>mode('Index 100').props.onClick());
act(()=>root().findByProps({'aria-label':'Reverse monthly order'}).props.onClick());
assert.equal(root().findByType('thead').findAllByType('th')[1].children[0],"Feb '22");
let exported:Blob|undefined;
(globalThis as any).URL.createObjectURL=(blob:Blob)=>{exported=blob;return 'blob:test';};
(globalThis as any).URL.revokeObjectURL=()=>{};
(globalThis as any).document={createElement:()=>({click(){},href:'',download:''})};
const csv=root().findAllByType('button').find((b:any)=>b.children.includes('CSV'));
act(()=>csv.props.onClick());
assert.ok(exported);
const text=await exported!.text();
assert.ok(text.includes('2022-02')&&text.includes('2026-10'));
assert.ok(text.includes('Visits')&&text.includes('Fill'));
console.log('Atlas component: all months, date independence, local selection, search, modes, order and CSV passed.');
tree.unmount();
